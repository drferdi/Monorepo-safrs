// Generates apps/web/src/lib/bot-templates.generated.ts from the vendored
// Sentra Chief of Staff Production Starter (packages/bot-templates).
// Core policy layers apply to every bot; each featured role contributes its
// ROLE.md operating contract. Re-run after editing the source templates:
//   node scripts/generate-bot-templates.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const src = join(root, "packages", "bot-templates");
const out = join(root, "apps", "web", "src", "lib", "bot-templates.generated.ts");

const coreFiles = [
  "00_SYSTEM_CORE.md",
  "10_CHIEF_OF_STAFF_CONTRACT.md",
  "20_EVIDENCE_POLICY.md",
  "30_APPROVAL_POLICY.md",
  "40_AUTOMATION_POLICY.md",
];
const core = coreFiles
  .map((name) => readFileSync(join(src, "core", name), "utf8").trim())
  .join("\n\n---\n\n");

const registry = JSON.parse(readFileSync(join(src, "templates", "registry.json"), "utf8"));
const featured = registry.templates.filter((entry) => entry.featured);

const templates = featured.map((entry) => {
  const dir = join(
    src,
    entry.path.replace("templates/", "templates/").replace("/template.json", ""),
  );
  const template = JSON.parse(readFileSync(join(dir, "template.json"), "utf8"));
  const role = readFileSync(join(dir, "ROLE.md"), "utf8").trim();
  return {
    id: template.id,
    title: template.identity.title,
    shortTitle: template.identity.shortTitle,
    icon: template.identity.icon,
    category: template.identity.category,
    description: template.mission.primaryOutcome,
    role,
  };
});

const banner = `// AUTO-GENERATED by scripts/generate-bot-templates.mjs — do not edit by hand.
// Source of truth: packages/bot-templates (Sentra Chief of Staff Production Starter v${registry.version}).
`;
const body = `${banner}
export interface GeneratedBotTemplate {
  id: string;
  title: string;
  shortTitle: string;
  icon: string;
  category: string;
  description: string;
  role: string;
}

export const CORE_INSTRUCTIONS: string = ${JSON.stringify(core)};

export const GENERATED_BOT_TEMPLATES: GeneratedBotTemplate[] = ${JSON.stringify(templates, null, 2)};
`;

writeFileSync(out, body);
console.log(`Wrote ${templates.length} featured templates + core (${core.length} chars) to ${out}`);
